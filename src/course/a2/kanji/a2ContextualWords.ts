/**
 * The word each contextual kanji actually lives in.
 *
 * Keyed by `KanjiRow.sense`, so the 120 rows share 98 words (名 and 前 both
 * belong to `namae`). Every `word` is the real, standard Japanese orthography
 * for that lexeme — a genuine word a learner could look up in a dictionary.
 * Some words contain kanji that the A2 course does not teach (e.g. 束 in 約束,
 * 利 in 便利); the ruby annotation renders `wordKana` above the whole word,
 * so the learner is never asked to *read* an untaught glyph on their own.
 * The trade-off is deliberate: an untaught glyph inside a correctly-read real
 * word is harmless, whereas a fake 交ぜ書き form (e.g. "便り" read as べんり)
 * teaches something false. One exception: 友だち is kept in mixed form because
 * that orthography is genuinely standard in real Japanese.
 *
 * `wordKana` is the whole word's reading and is what the ruby renders above it.
 */
export interface A2ContextualWord {
  /** The real-word display form whose reading is {@link wordKana}, e.g. 便利, 話す, 友だち. */
  readonly word: string;
  /** The whole word in kana, e.g. ともだち. */
  readonly wordKana: string;
}

